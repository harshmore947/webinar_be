const cleanupOldReminders = async () => {
  try {
    const yesterday = new Date(Date.now() - 24 * 60 * 60 * 1000);

    const result = await ReminderModel.deleteMany({
      reminderTime: { $lt: yesterday },
      isEmailSent: true,
    });

    if (result.deletedCount > 0) {
      logInfo(`Cleaned up ${result.deletedCount} old reminders`);
    }
  } catch (error) {
    logError("Error in cleanupOldReminders:", error as Error);
  }
};

/**
 * Auto-generate certificates for webinars that have ended
 */
const autoGenerateCertificates = async () => {
  try {
    const now = new Date();
    const thirtyMinutesAgo = new Date(now.getTime() - 30 * 60 * 1000);

    // Find webinars that ended in the last 30 minutes and haven't had certificates generated
    const eligibleWebinars = await WebinarModel.find({
      endDate: { $gte: thirtyMinutesAgo, $lte: now },
      $or: [
        { "certificateConfig.autoGenerated": { $ne: true } },
        { "certificateConfig.autoGenerated": { $exists: false } },
      ],
      "certificateConfig.isEnabled": true,
    });

    if (eligibleWebinars.length === 0) {
      return;
    }

    logInfo(
      `Found ${eligibleWebinars.length} webinars eligible for auto certificate generation`
    );

    for (const webinar of eligibleWebinars) {
      try {
        logInfo(
          `Auto-generating certificates for webinar: ${webinar.title} (${webinar._id})`
        );

        // Generate certificates for all qualified attendees
        let successCount = 0;
        let failCount = 0;

        if (webinar.attendedUsers && webinar.attendedUsers.length > 0) {
          for (const attendee of webinar.attendedUsers) {
            // Only generate for users who attended for at least 30 minutes
            if ((attendee as any).totalDuration >= 30) {
              try {
                const result =
                  await SimpleCertificateService.requestCertificateForUser(
                    (attendee as any).userId.toString(),
                    (webinar._id as any).toString()
                  );

                if (result.success) {
                  successCount++;
                } else {
                  failCount++;
                  logError(
                    `Failed to generate certificate for user ${
                      (attendee as any).userId
                    }: ${result.error}`
                  );
                }
              } catch (error) {
                failCount++;
                logError(
                  `Error generating certificate for user ${
                    (attendee as any).userId
                  }:`,
                  error as Error
                );
              }
            }
          }
        }

        if (successCount > 0) {
          logInfo(
            `Successfully initiated certificate generation for ${successCount} users in webinar ${webinar._id}`
          );

          // Mark webinar as having auto-generated certificates
          await WebinarModel.findByIdAndUpdate(webinar._id, {
            "certificateConfig.autoGenerated": true,
            "certificateConfig.generatedAt": new Date(),
          });
        }

        if (failCount > 0) {
          logError(
            `Failed to generate certificates for ${failCount} users in webinar ${webinar._id}`
          );
        }
      } catch (error) {
        logError(
          `Error generating certificates for webinar ${webinar._id}:`,
          error as Error
        );
      }
    }
  } catch (error) {
    logError("Error in autoGenerateCertificates:", error as Error);
  }
};

