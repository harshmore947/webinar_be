import cron from "node-cron";
import ReminderModel from "../models/Reminder.model";
import WebinarModel from "../models/Webinar.model";
import { sendMail } from "./mailer";
import { generateReminderEmailTemplate } from "./emailTemplates";
import { logError, logInfo } from "./logger";
import { SimpleCertificateService } from "./simpleCertificateService";

const sendReminderEmails = async () => {
  try {
    const now = new Date();
    const fiveMinutesFromNow = new Date(now.getTime() + 5 * 60 * 1000);

    // Find reminders that should be sent in the next 5 minutes
    const dueReminders = await ReminderModel.find({
      reminderTime: { $gte: now, $lte: fiveMinutesFromNow },
      isEmailSent: false,
    })
      .populate("userId", "firstName lastName email")
      .populate("webinarId", "title date description");

    if (dueReminders.length === 0) {
      return;
    }

    logInfo(`Found ${dueReminders.length} reminders to send`);

    for (const reminder of dueReminders) {
      try {
        const user = reminder.userId as any;
        const webinar = reminder.webinarId as any;

        if (!user || !webinar) {
          logError(
            `Missing user or webinar data for reminder: ${reminder._id.toString()}`
          );
          continue;
        }

        const subject = `Reminder: ${webinar.title}`;
        const webinarDate = new Date(webinar.date).toLocaleString();

        const emailTemplate = generateReminderEmailTemplate({
          firstName: user.firstName,
          webinarTitle: webinar.title,
          webinarDate,
          webinarDescription: webinar.description,
        });

        await sendMail({
          to: user.email,
          subject,
          html: emailTemplate,
        });

        // Mark reminder as sent
        reminder.isEmailSent = true;
        await reminder.save();

        logInfo(
          `Reminder email sent to ${user.email} for webinar: ${webinar.title}`
        );
      } catch (emailError) {
        logError(
          `Failed to send reminder email for reminder ${reminder._id}:`,
          emailError as Error
        );
      }
    }
  } catch (error) {
    logError("Error in sendReminderEmails:", error as Error);
  }
};

