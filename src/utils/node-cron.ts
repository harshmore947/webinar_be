export const startReminderCron = () => {
  // Send reminder emails every minute
  cron.schedule("*/1 * * * *", sendReminderEmails, {
    timezone: "UTC",
  });

  // Clean up old reminders daily at midnight
  cron.schedule("0 0 * * *", cleanupOldReminders, {
    timezone: "UTC",
  });

  logInfo("Reminder cron jobs started successfully");
};

export const startCertificateCron = () => {
  // Auto-generate certificates every 5 minutes for recently ended webinars
  cron.schedule("*/5 * * * *", autoGenerateCertificates, {
    timezone: "UTC",
  });

  // Monitor certificate job statuses every 10 minutes
  cron.schedule("*/10 * * * *", monitorCertificateJobs, {
    timezone: "UTC",
  });

  logInfo("Certificate cron jobs started successfully");
};

export const startAllCronJobs = () => {
  startReminderCron();
  startCertificateCron();
  logInfo("All cron jobs started successfully");
};
